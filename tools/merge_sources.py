"""Map citation keys that point at the same source onto one key.

The research dossiers each have their own source list (A1, B3, ...). When
two lists contain the same URL (or the same DOI), the later key is mapped
to the first one, so the bibliography lists the source once. Writes
book/src-map.typ, which template.typ imports.

Run from the project root: python3 tools/merge_sources.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def entries(path):
    """Yield (key, url, doi) for each top-level entry of a Hayagriva file."""
    key, url, doi = None, None, None
    for line in open(path, encoding="utf-8"):
        m = re.match(r'^([A-Za-z0-9_-]+):\s*$', line)
        if m:
            if key:
                yield key, url, doi
            key, url, doi = m.group(1), None, None
            continue
        m = re.search(r'value:\s*"?([^"\s]+)"?', line)
        if m and url is None and "http" in m.group(1):
            url = m.group(1)
        m = re.search(r'^\s*url:\s*"?(https?://[^"\s]+)"?', line)
        if m and url is None:
            url = m.group(1)
        m = re.search(r'doi:\s*"?([^"\s]+)"?', line)
        if m:
            doi = m.group(1).lower()
    if key:
        yield key, url, doi


def norm_url(u):
    u = u.lower().rstrip("/")
    u = re.sub(r'^https?://(www\.)?', '', u)
    return u.split("#")[0]


def main():
    seen = {}
    mapping = {}
    files = sorted(glob.glob(os.path.join(ROOT, "research", "*-sources.yml")))
    for path in files:
        for key, url, doi in entries(path):
            ids = []
            if doi:
                ids.append("doi:" + doi)
            if url:
                ids.append("url:" + norm_url(url))
            canon = next((seen[i] for i in ids if i in seen), None)
            if canon and canon != key:
                mapping[key] = canon
            else:
                for i in ids:
                    seen.setdefault(i, key)
    out = os.path.join(ROOT, "book", "src-map.typ")
    with open(out, "w") as f:
        f.write("// Generated by tools/merge_sources.py. Do not edit.\n")
        f.write("#let src-map = (\n")
        if not mapping:
            f.write("  :\n")
        for k in sorted(mapping):
            f.write(f'  "{k}": "{mapping[k]}",\n')
        f.write(")\n")
    print(f"{len(files)} files, {len(mapping)} duplicate keys mapped -> {out}")


if __name__ == "__main__":
    main()
